// Builds dist/data/enemy-pages.js: per enemy on the enemy view, the wiki infobox fire damage
// multiplier and stagger threshold, its subfaction (faction picks guide id) and the Korean/English
// summaries of the wiki Spawning and Behavior sections.
// Inputs: db/source/wiki_enemy_pages.json (scripts/fetch-enemy-pages.mjs) and
// db/source/enemy_behavior_korean.json (summaries, each tied to the wiki revision it was written from).
// Usage: node scripts/build-enemy-pages.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { enemies } from '../dist/data/combat-data.js';
import { factionGuides } from '../dist/data/faction-data.js';
import { pageTitle } from './enemy-page-title.mjs';

const read = async path => JSON.parse(await readFile(new URL(path, import.meta.url), 'utf8'));
const wiki = await read('../db/source/wiki_enemy_pages.json');
const summaries = await read('../db/source/enemy_behavior_korean.json');
// Wiki infobox `faction` -> faction picks guide id (the three main factions have none).
const SUBFACTIONS = {
  'Predator Strain': 'predator', 'Spore Burst Strain': 'spore-burst', 'Rupture Strain': 'rupture', 'Caustic Strain': 'caustic', 'Noxious Strain': 'noxious',
  'Jet Brigade': 'jet-brigade', 'Incineration Corps': 'incineration', 'Cyborg Legion': 'cyborgs',
  'Vote Snatchers': 'vote-snatchers', 'Mindless Masses': 'mindless', 'Appropriators': 'appropriators', 'Invasion Fleet': 'invasion',
};
const MAIN = new Set(['Terminids', 'Automatons', 'Illuminate']);
const guideIds = new Set(factionGuides.map(guide => guide.id));
const number = value => value == null ? null : Number.isFinite(Number(value)) ? Number(value) : (() => { throw new Error(`not a number: ${value}`); })();

const out = {};
const problems = [];
for (const enemy of enemies) {
  const title = pageTitle(enemy);
  const page = wiki.pages[title];
  if (!page) { problems.push(`${enemy.id}: wiki page ${title} not fetched`); continue; }
  const summary = summaries[title];
  if (!summary) problems.push(`${title}: no summary in enemy_behavior_korean.json`);
  else if (summary.revision !== page.revision) problems.push(`${title}: summary written from revision ${summary.revision}, wiki is now ${page.revision} - update the summary`);
  if (page.faction && !MAIN.has(page.faction) && !SUBFACTIONS[page.faction]) problems.push(`${title}: unknown faction ${page.faction}`);
  const subfaction = SUBFACTIONS[page.faction] ?? null;
  if (subfaction && !guideIds.has(subfaction)) problems.push(`${title}: no faction guide ${subfaction}`);
  const lines = key => summary?.[key] ?? [];
  out[enemy.id] = {
    page: title, revision: page.revision, subfaction,
    fireMult: number(page.fireMult), staggerReq: number(page.staggerReq),
    spawning: lines('spawning').map(line => line.ko), spawningEn: lines('spawning').map(line => line.en),
    behavior: lines('behavior').map(line => line.ko), behaviorEn: lines('behavior').map(line => line.en),
  };
}
if (problems.length) throw new Error(`build-enemy-pages:\n  ${problems.join('\n  ')}`);
await writeFile(new URL('../dist/data/enemy-pages.js', import.meta.url), `// Generated by scripts/build-enemy-pages.mjs from Helldivers Wiki enemy pages (infobox fire_mult,
// stagger_req, faction; Spawning and Behavior sections summarized in db/source/enemy_behavior_korean.json).
// Do not edit.
export const enemyPagesCheckedAt = ${JSON.stringify(wiki.retrievedAt)};
export const enemyPages = ${JSON.stringify(out, null, 1)};
`);
console.log(`${Object.keys(out).length} enemies`);
