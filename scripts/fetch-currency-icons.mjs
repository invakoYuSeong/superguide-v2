// Downloads the wiki's Medal, Super Credit, sample and Requisition Slip icons (the files its Currency template shows)
// into dist/assets/icons/, safety-checked, and writes dist/data/currency-icons.js for the warbond
// view and the ship module tab.
// Usage: node scripts/fetch-currency-icons.mjs
import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { validateSvg } from './svg-safety.mjs';

const API = 'https://helldivers.wiki.gg/api.php';
const UA = 'HD2FieldGuide/2.0 (fan site data check; contact via github modocracy)';
const FILES = { medal: 'Medal.svg', 'super-credit': 'Super Credit.svg', 'common-sample': 'Common Sample Logo.svg', 'rare-sample': 'Rare Sample Logo.svg', 'super-sample': 'Super Sample Logo.svg', 'requisition-slip': 'Requisition Slip.svg' };
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
async function patient(url) {
  for (let attempt = 0; ; attempt++) {
    const res = await fetch(url, { headers: { 'User-Agent': UA }, signal: AbortSignal.timeout(60000) });
    if (res.ok && !(res.headers.get('content-type') || '').includes('json')) return res;
    if (res.ok) { const body = await res.clone().json(); if (!body.error) return res; }
    if (attempt === 5) throw new Error(`${res.status} ${url}`);
    await sleep(20000 * (attempt + 1));
  }
}
const icons = {};
for (const [id, file] of Object.entries(FILES)) {
  const query = new URLSearchParams({ action: 'query', prop: 'imageinfo', iiprop: 'url', titles: `File:${file}`, format: 'json', formatversion: '2' });
  const info = (await (await patient(`${API}?${query}`)).json()).query.pages[0].imageinfo[0];
  // A standard SVG 1.1 DOCTYPE line (no entities) is dropped: the safety check allows no DTD.
  const raw = Buffer.from(await (await patient(info.url)).arrayBuffer()).toString('utf8');
  const bytes = Buffer.from(raw.replace(/<!DOCTYPE svg PUBLIC "-\/\/W3C\/\/DTD SVG 1\.1\/\/EN" "http:\/\/www\.w3\.org\/Graphics\/SVG\/1\.1\/DTD\/svg11\.dtd">\s*/, ''), 'utf8');
  validateSvg(bytes, { name: file });
  await writeFile(new URL(`../dist/assets/icons/${id}.svg`, import.meta.url), bytes);
  icons[id] = { src: `./assets/icons/${id}.svg`, source: `https://helldivers.wiki.gg/wiki/File:${file.replaceAll(' ', '_')}`, sha256: createHash('sha256').update(bytes).digest('hex') };
  console.log(id, bytes.length);
  await sleep(2000);
}
await writeFile(new URL('../dist/data/currency-icons.js', import.meta.url), `// Generated by scripts/fetch-currency-icons.mjs from the Helldivers Wiki Medal, Super Credit, sample and Requisition Slip icons
// (CC BY-NC-SA 4.0). Do not edit.
export const currencyIcons = ${JSON.stringify(icons, null, 1)};
`);
