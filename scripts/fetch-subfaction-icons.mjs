// Downloads the wiki icon of every enemy subfaction in the faction picks (the infobox image of its
// wiki page) into dist/assets/subfactions/<guide id>.svg, safety-checked, and writes
// dist/data/subfaction-icons.js. The view tints them in the faction colour (CSS mask).
// Usage: node scripts/fetch-subfaction-icons.mjs
import { writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { validateSvg } from './svg-safety.mjs';

const API = 'https://helldivers.wiki.gg/api.php';
const UA = 'HD2FieldGuide/2.0 (fan site data check; contact via github modocracy)';
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
// Faction guide id -> wiki page of the subfaction.
const PAGES = {
  predator: 'Predator Strain', 'spore-burst': 'Spore Burst Strain', rupture: 'Rupture Strain', caustic: 'Caustic Strain', noxious: 'Noxious Strain',
  'jet-brigade': 'Jet Brigade', incineration: 'Incineration Corps', cyborgs: 'Cyborg Legion',
  'vote-snatchers': 'Vote Snatchers', mindless: 'Mindless Masses', appropriators: 'Appropriators', invasion: 'Invasion Fleet',
};
// wiki.gg answers 429 (or a ratelimited error) when asked too fast: wait and try again.
async function patient(url) {
  for (let attempt = 0; ; attempt++) {
    const res = await fetch(url, { headers: { 'User-Agent': UA }, signal: AbortSignal.timeout(60000) });
    const limited = res.status === 429 || (res.headers.get('content-type') || '').includes('json') && (await res.clone().json()).error?.code === 'ratelimited';
    if (!limited && res.ok) return res;
    if (attempt === 5) throw new Error(`${res.status} ${url}`);
    await sleep(20000 * (attempt + 1));
  }
}
const get = async params => (await patient(`${API}?${new URLSearchParams({ format: 'json', formatversion: '2', ...params })}`)).json();

const { query } = await get({ action: 'query', prop: 'revisions', rvprop: 'ids|content', rvslots: 'main', redirects: '1', titles: Object.values(PAGES).join('|') });
const byTitle = new Map(query.pages.map(page => [page.title, page]));
await mkdir(new URL('../dist/assets/subfactions/', import.meta.url), { recursive: true });
const icons = {};
for (const [id, title] of Object.entries(PAGES)) {
  const page = byTitle.get(title);
  const image = /\|\s*image\s*=\s*([^\n|]+)/.exec(page?.revisions?.[0].slots.main.content ?? '')?.[1].trim();
  if (!image) throw new Error(`${title}: no infobox image`);
  await sleep(3000);
  const info = (await get({ action: 'query', prop: 'imageinfo', iiprop: 'url', titles: `File:${image}` })).query.pages[0].imageinfo[0];
  // A standard SVG 1.1 DOCTYPE line (no entities) is dropped: the safety check allows no DTD.
  const raw = Buffer.from(await (await patient(info.url)).arrayBuffer()).toString('utf8');
  const bytes = Buffer.from(raw.replace(/<!DOCTYPE svg PUBLIC "-\/\/W3C\/\/DTD SVG 1\.1\/\/EN" "http:\/\/www\.w3\.org\/Graphics\/SVG\/1\.1\/DTD\/svg11\.dtd">\s*/, ''), 'utf8');
  validateSvg(bytes, { name: image });
  await writeFile(new URL(`../dist/assets/subfactions/${id}.svg`, import.meta.url), bytes);
  icons[id] = { src: `./assets/subfactions/${id}.svg`, page: title, revision: page.revisions[0].revid, source: `https://helldivers.wiki.gg/wiki/File:${image.replaceAll(' ', '_')}`, sha256: createHash('sha256').update(bytes).digest('hex') };
  console.log(id, image);
}
await writeFile(new URL('../dist/data/subfaction-icons.js', import.meta.url), `// Generated by scripts/fetch-subfaction-icons.mjs from Helldivers Wiki subfaction icons
// (CC BY-NC-SA 4.0). Key: faction guide id. Do not edit.
export const subfactionIcons = ${JSON.stringify(icons, null, 1)};
`);
