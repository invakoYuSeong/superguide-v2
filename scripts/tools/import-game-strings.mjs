// Copies the game's official US English -> Korean string table into the repository as
// db/source/game_strings_ko.tsv, so anyone can rebuild the site's game names with
// `node scripts/build-game-names.mjs`. Voice lines (they start with a "{0.00->" timing
// code) and texts longer than 300 characters (news, lore) are left out; names and
// effect descriptions stay. Run it after a game update on a PC that has the table.
// The input is tab-separated (id, english, korean) with a stats.json next to it naming
// the game build. With --planets <행성.json> (the game's planet table: planet names in
// Korean and English, internal biome, biome description) it also writes
// db/source/game_planets_ko.json.
// Usage: node scripts/tools/import-game-strings.mjs <official_strings_us_ko.tsv> [--planets <행성.json>]
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';

const MAX_LENGTH = 300;
const input = process.argv[2];
if (!input) throw new Error('Usage: node scripts/tools/import-game-strings.mjs <official_strings_us_ko.tsv> [--planets <행성.json>]');
const planetsFile = process.argv.includes('--planets') ? process.argv[process.argv.indexOf('--planets') + 1] : null;
const build = String(JSON.parse(await readFile(join(dirname(input), 'stats.json'), 'utf8')).build);

// The table quotes a field that holds quotes, tabs or line breaks ("" inside stands for ").
function parseTsv(text) {
  const records = [];
  let record = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (quoted) {
      if (char === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (char === '"') quoted = false;
      else field += char;
    } else if (char === '"' && field === '') quoted = true;
    else if (char === '\t') { record.push(field); field = ''; }
    else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[i + 1] === '\n') i++;
      record.push(field); records.push(record); record = []; field = '';
    } else field += char;
  }
  if (field || record.length) { record.push(field); records.push(record); }
  return records;
}

const rows = new Map();
for (const [, english = '', korean = ''] of parseTsv(await readFile(input, 'utf8')).slice(1)) {
  const en = english.trim(), ko = korean.trim();
  // Rows kept must fit one line of the output table.
  if (!en || !ko || en.startsWith('{') || en.length > MAX_LENGTH || /[\t\r\n]/.test(en + ko) || rows.has(en)) continue;
  rows.set(en, ko);
}
const sorted = [...rows].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
await writeFile(new URL('../../db/source/game_strings_ko.tsv', import.meta.url),
  `#build\t${build}\n#note\tHelldivers 2 official strings (US English -> Korean) from the game files, without voice lines and texts over ${MAX_LENGTH} characters. Generated by scripts/tools/import-game-strings.mjs; do not edit.\n`
  + sorted.map(([en, ko]) => `${en}\t${ko}`).join('\n') + '\n');
console.log(`game build ${build}: ${sorted.length} strings`);

// Planet names and biome descriptions from the game's planet table.
if (planetsFile) {
  const table = JSON.parse(await readFile(planetsFile, 'utf8'));
  if (String(table.game_build) !== build) throw new Error(`${planetsFile} is game build ${table.game_build}, the string table ${build}`);
  const planets = table['행성'].filter(row => row['한국어'] && row['영어']).map(row => ({ ko: row['한국어'], en: row['영어'], biome: row['생물군계'].split(' ')[0] }));
  // A biome's description is the one most of its planets carry (a few planets have their own story text).
  const biomes = {};
  for (const row of table['행성'].filter(row => row['설명(한국어)'] && row['설명(영어)'])) {
    const biome = row['생물군계'].split(' ')[0];
    const key = `${row['설명(영어)']}\t${row['설명(한국어)']}`;
    ((biomes[biome] ??= {})[key] = (biomes[biome][key] || 0) + 1);
  }
  const descriptions = Object.fromEntries(Object.entries(biomes).map(([biome, counts]) => {
    const [en, ko] = Object.entries(counts).sort((a, b) => b[1] - a[1])[0][0].split('\t');
    return [biome, { en, ko }];
  }));
  const out = { note: 'Generated by scripts/tools/import-game-strings.mjs --planets from the game\'s planet table. Do not edit.', build, biomes: descriptions, planets };
  await writeFile(new URL('../../db/source/game_planets_ko.json', import.meta.url), JSON.stringify(out, null, 1) + '\n');
  console.log(`${planets.length} planets, ${Object.keys(descriptions).length} biome descriptions`);
}
