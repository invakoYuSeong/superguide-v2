// Downloads the wiki's difficulty icons 1 to 10 (the files its Difficulty template shows, Module:Difficulty)
// into dist/assets/difficulty/, safety-checked, and writes dist/data/difficulty-icons.js for the enemy view.
// Usage: node scripts/fetch-difficulty-icons.mjs
import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { validateSvg } from './svg-safety.mjs';

const API = 'https://helldivers.wiki.gg/api.php';
const UA = 'HD2FieldGuide/2.0 (fan site data check; contact via github modocracy)';
// Module:Difficulty icon names, difficulty 1 to 10.
const FILES = ['Trivial', 'Easy', 'Medium', 'Challenging', 'Hard', 'Extreme', 'Suicide', 'Impossible', 'Helldive', 'Super_Helldive'].map(name => `${name}_Difficulty_Icon.svg`);
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
async function patient(url) {
  for (let attempt = 0; ; attempt++) {
    const res = await fetch(url, { headers: { 'User-Agent': UA }, signal: AbortSignal.timeout(60000) });
    if (res.ok && !(res.headers.get('content-type') || '').includes('json')) return res;
    if (res.ok) { const body = await res.clone().json(); if (!body.error) return res; }
    if (attempt === 5) throw new Error(`${res.status} ${url}`);
    await sleep(20000 * (attempt + 1));
  }
}
await mkdir(new URL('../dist/assets/difficulty/', import.meta.url), { recursive: true });
const icons = {};
for (const [i, file] of FILES.entries()) {
  const level = i + 1;
  const query = new URLSearchParams({ action: 'query', prop: 'imageinfo', iiprop: 'url', titles: `File:${file}`, format: 'json', formatversion: '2' });
  const info = (await (await patient(`${API}?${query}`)).json()).query.pages[0].imageinfo[0];
  // A standard SVG 1.1 DOCTYPE line (no entities) is dropped: the safety check allows no DTD.
  const raw = Buffer.from(await (await patient(info.url)).arrayBuffer()).toString('utf8');
  const bytes = Buffer.from(raw.replace(/<!DOCTYPE svg PUBLIC "-\/\/W3C\/\/DTD SVG 1\.1\/\/EN" "http:\/\/www\.w3\.org\/Graphics\/SVG\/1\.1\/DTD\/svg11\.dtd">\s*/, ''), 'utf8');
  validateSvg(bytes, { name: file });
  await writeFile(new URL(`../dist/assets/difficulty/${level}.svg`, import.meta.url), bytes);
  icons[level] = { src: `./assets/difficulty/${level}.svg`, source: `https://helldivers.wiki.gg/wiki/File:${file}`, sha256: createHash('sha256').update(bytes).digest('hex') };
  console.log(level, file, bytes.length);
  await sleep(2000);
}
await writeFile(new URL('../dist/data/difficulty-icons.js', import.meta.url), `// Generated by scripts/fetch-difficulty-icons.mjs from the Helldivers Wiki difficulty icons
// (CC BY-NC-SA 4.0). Do not edit.
export const difficultyIcons = ${JSON.stringify(icons, null, 1)};
`);
