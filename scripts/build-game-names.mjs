// Picks the game's own Korean for every English string this site needs from
// db/source/game_strings_ko.tsv into db/source/game_names_ko.json (see the naming
// rule in AGENTS.md). Strings are matched exactly, then ignoring case. When a new
// booster, condition, mission or rename is added to the db/source/*.json lists below,
// run this, then the matching build-* script. The table itself is refreshed after a
// game update with scripts/tools/import-game-strings.mjs.
// Usage: node scripts/build-game-names.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { shipModules } from '../dist/data/ship-modules.js';
import { warbonds } from '../dist/data/warbonds.js';
import { gameTileKeys } from './warbond-parse.mjs';

// Warbond cosmetic and booster tiles (the kinds build-warbonds.mjs names in Korean).
const TILE_KINDS = ['booster', 'emote', 'victory-pose', 'player-card', 'cape', 'title', 'pattern'];

const source = async name => JSON.parse(await readFile(new URL(`../db/source/${name}`, import.meta.url), 'utf8'));
const lines = (await readFile(new URL('../db/source/game_strings_ko.tsv', import.meta.url), 'utf8')).split('\n');
const build = lines.find(line => line.startsWith('#build\t'))?.split('\t')[1];
if (!build) throw new Error('db/source/game_strings_ko.tsv has no #build line');
const exact = new Map(), folded = new Map();
for (const line of lines.filter(line => line && !line.startsWith('#'))) {
  const [english, korean] = line.split('\t');
  exact.set(english, korean);
  if (!folded.has(english.toLowerCase())) folded.set(english.toLowerCase(), korean);
}

// Every English string the site takes Korean from, grouped by where it is used.
const boosters = Object.values((await source('booster_korean.json')).boosters);
const objectives = Object.values((await source('structure_objectives.json')).structures).flat();
const planet = await source('planet_korean.json');
const targets = await source('game_name_targets.json');
const planetEntries = [...planet.conditions, ...planet.gloom, ...planet.special, ...planet.modifiers, ...planet.events];
const wanted = {
  shipModules: shipModules.map(module => module.en),
  boosters: boosters.flatMap(booster => [booster.name, booster.description]).filter(Boolean),
  objectives: [...new Set(objectives.map(entry => entry.game))],
  planets: [...new Set(planetEntries.flatMap(entry => [entry.name, entry.description]))],
  status: planet.status.map(entry => entry.name).filter(Boolean),
  names: [...new Set(Object.entries(targets).filter(([key]) => key !== 'note').flatMap(([, group]) => Object.values(group).map(entry => entry.game)))],
};

const out = { note: 'Generated by scripts/build-game-names.mjs from db/source/game_strings_ko.tsv. Do not edit.', build, strings: {} };
const missing = [];
for (const [group, keys] of Object.entries(wanted)) {
  out.strings[group] = {};
  for (const key of keys) {
    const korean = exact.get(key) ?? folded.get(key.toLowerCase());
    if (korean) out.strings[group][key] = korean; else missing.push(`${group}: ${key}`);
  }
}
// Warbond tiles: every English string a tile may carry; only the ones the game table has are kept
// (a tile without one keeps its Namu Wiki name or stays English).
out.strings.warbondItems = {};
for (const key of [...new Set(warbonds.flatMap(warbond => warbond.pages.flatMap(page => page.items)).filter(item => TILE_KINDS.includes(item.kind)).flatMap(gameTileKeys))].sort()) {
  const korean = exact.get(key) ?? folded.get(key.toLowerCase());
  if (korean) out.strings.warbondItems[key] = korean;
}
if (missing.length) throw new Error(`No Korean in db/source/game_strings_ko.tsv for:\n  ${missing.join('\n  ')}\nCheck the English against the table (it is the game's exact text).`);
await writeFile(new URL('../db/source/game_names_ko.json', import.meta.url), JSON.stringify(out, null, 1) + '\n');
console.log(`game build ${build}: ${Object.values(out.strings).reduce((sum, group) => sum + Object.keys(group).length, 0)} strings`);
