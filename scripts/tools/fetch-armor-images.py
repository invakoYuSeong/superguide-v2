"""Download the armor page images (Helldivers Wiki): body armor renders and passive icons.

Reads dist/data/armor.js (run scripts/build-armor.mjs first): every armor carries the `image`
file name from its {{Infobox Armor}} and every passive the `icon` from {{Infobox Armor Passive}}.
  - Armor renders: thumbnail from the MediaWiki API, transparent margins trimmed, fitted inside
    BOX (2x the list thumbnail; never upscaled), saved as dist/assets/armor/<slug>.webp.
  - Passive icons: original SVG bytes, safety-checked (scripts/svg-safety.mjs, max 50 KB).
Writes dist/data/armor-images.js (file name → src/size/sha1/source URL) and the files that could
not be fetched (the page shows those without a picture). Files whose wiki sha1 did not change are
kept as they are; files no longer referenced are removed from dist/assets/armor.
Helpers (curl download, imageinfo, WebP encoding, SVG checks) are shared with
fetch-warbond-item-images.py. Images: Helldivers Wiki, CC BY-NC-SA 4.0.
Usage: python3 scripts/tools/fetch-armor-images.py [--force]   (requires curl and Pillow with WebP)
"""
import hashlib, importlib.util, json, pathlib, re, subprocess, sys, time

root = pathlib.Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('warbond_images', root / 'scripts' / 'tools' / 'fetch-warbond-item-images.py')
shared = importlib.util.module_from_spec(spec)
spec.loader.exec_module(shared)

from PIL import Image

_get = shared.get


def patient_get(url, tries=6):
    """wiki.gg answers 429 when asked too fast; wait and try again instead of failing the run."""
    for attempt in range(tries):
        try:
            return _get(url)
        except subprocess.CalledProcessError:
            if attempt == tries - 1:
                raise
            time.sleep(20 * (attempt + 1))


shared.get = patient_get  # image_info() in the shared module looks `get` up at call time

out_dir = root / 'dist' / 'assets' / 'armor'
module_path = root / 'dist' / 'data' / 'armor-images.js'
BOX = (180, 360)  # list thumbnail is about 72 x 144 CSS px; 2.5x for sharp phones


def wanted():
    """(armor render file names, passive icon file names) from dist/data/armor.js."""
    script = ('import { armors, armorPassives } from "./dist/data/armor.js";'
              'console.log(JSON.stringify([armors.map(a => a.image).filter(Boolean), armorPassives.map(p => p.icon).filter(Boolean)]))')
    renders, icons = json.loads(subprocess.run(['node', '--input-type=module', '-e', script], cwd=root,
                                               capture_output=True, text=True, check=True).stdout)
    return sorted(set(renders)), sorted(set(icons))


def read_module():
    if not module_path.exists():
        return {}
    match = re.search(r'export const armorImages = (\{.*?\n\});', module_path.read_text(encoding='utf-8'), re.S)
    return json.loads(re.sub(r',\n\}$', '\n}', match.group(1))) if match else {}


def unchanged(name, entry, meta):
    """Keep a local file only when the wiki file and the bytes on disk are what was recorded."""
    if not entry or entry.get('sha1') != meta.get('sha1'):
        return False
    target = root / 'dist' / entry['src'].removeprefix('./')
    if not target.is_file() or hashlib.sha256(target.read_bytes()).hexdigest() != entry.get('sha256'):
        return False
    if target.suffix == '.svg':
        return list(shared.safe_svg(target.read_bytes(), entry)) == [entry['width'], entry['height']]
    with Image.open(target) as image:
        return image.format == 'WEBP' and list(image.size) == [entry['width'], entry['height']] and image.width <= BOX[0] and image.height <= BOX[1]


def write_module(entries, missing):
    body = ',\n'.join(f'  {json.dumps(k, ensure_ascii=False)}: {json.dumps({**v, "source": shared.source_url(k)}, ensure_ascii=False)}' for k, v in sorted(entries.items()))
    module_path.write_text(
        '// Generated by scripts/tools/fetch-armor-images.py from Helldivers Wiki armor renders and passive icons\n'
        '// (CC BY-NC-SA 4.0; source: https://helldivers.wiki.gg/wiki/File:<file name>).\n'
        '// Renders: trimmed, resized, WebP. Passive icons: original SVG bytes, safety-checked.\n'
        '// Key: the wiki file name used by the armor infobox. Do not edit by hand.\n'
        f'export const armorImages = {{\n{body}\n}};\n'
        f'export const armorImagesMissing = {json.dumps(sorted(missing), ensure_ascii=False)};\n',
        encoding='utf-8', newline='\n')


def main():
    if set(sys.argv[1:]) - {'--force'}:
        sys.exit('Usage: fetch-armor-images.py [--force]')
    renders, icons = wanted()
    names = renders + icons
    slugs = {}
    for name in names:
        s = shared.slug(name)
        if s in slugs:
            sys.exit(f'Slug collision: {name!r} and {slugs[s]!r}')
        slugs[s] = name
    previous = {} if '--force' in sys.argv else read_module()
    meta = shared.image_info(names)
    print(f'{len(renders)} armor renders and {len(icons)} passive icons, {len(meta)} found on the wiki')
    entries, missing, todo = {}, [], {}
    for name in names:
        m = meta.get(name)
        if not m:
            missing.append(name)
        elif unchanged(name, previous.get(name), m):
            entries[name] = previous[name]
        else:
            todo.setdefault(shared.bucket(m, BOX) if not name.lower().endswith('.svg') else 0, []).append(name)
    out_dir.mkdir(parents=True, exist_ok=True)
    fetched = 0
    for width, batch in sorted(todo.items()):
        thumbs = shared.image_info(batch, width) if width else meta
        for name in batch:
            m = thumbs.get(name)
            try:
                if not m:
                    raise ValueError('No imageinfo returned for the thumbnail')
                svg = name.lower().endswith('.svg')
                use_original = svg or width >= (m.get('width') or 0)
                raw = shared.get(m['url'] if use_original else m.get('thumburl') or m['url'])
                time.sleep(0.15)
                if svg:
                    w, h = shared.safe_svg(raw, m)
                    if hashlib.sha1(raw).hexdigest() != m.get('sha1'):
                        raise ValueError('Original SVG SHA-1 does not match imageinfo')
                    data = raw
                else:
                    data, (w, h), _ = shared.encode(raw, BOX)
            except Exception as error:  # a broken file on the wiki: show the armor without a picture
                print(f'  failed: {name}: {error}')
                missing.append(name)
                continue
            target = out_dir / f'{shared.slug(name)}.{"svg" if svg else "webp"}'
            target.write_bytes(data)
            entries[name] = {'src': f'./assets/armor/{target.name}', 'width': w, 'height': h,
                             'sha1': m.get('sha1'), 'sha256': hashlib.sha256(data).hexdigest()}
            fetched += 1
    keep = {pathlib.Path(e['src']).name for e in entries.values()}
    for stale in out_dir.iterdir():
        if stale.is_file() and stale.suffix in ('.webp', '.svg') and stale.name not in keep:
            stale.unlink()
    write_module(entries, missing)
    total = sum(p.stat().st_size for p in out_dir.iterdir())
    print(f'{len(entries)} images ({fetched} new or changed), {total:,} bytes in dist/assets/armor; missing {len(missing)}: {sorted(missing)}')


if __name__ == '__main__':
    main()
