// Builds dist/data/weapon-recoil.js: each weapon's base recoil (weapon drift and camera climb, horizontal /
// vertical, and where vertical recoil starts easing off) from db/source/otl_recoil.json (scripts/fetch-recoil.mjs),
// keyed 'gear/<id>' for primaries and secondaries and 'arsenal/<id>' for support weapons. A row matches by its
// full English name, else by the name without its code (CQC-72 Entrenchment Tool = CQC-73 on the site).
// Melee weapons (CQC-) are left out: their recoil row is a placeholder. Rows with no site weapon are listed,
// not an error (a new weapon shows up there first). Do not edit the output.
// Usage: node scripts/build-recoil.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { personalWeapons } from '../dist/data/personal-weapons.js';
import { stratagems } from '../dist/core/catalog.js';

const norm = text => String(text).toLowerCase().replace(/[^a-z0-9]/g, '');
const bare = text => norm(String(text).replace(/^\S+\s/, ''));

export async function buildRecoil() {
  const snapshot = JSON.parse(await readFile(new URL('../db/source/otl_recoil.json', import.meta.url), 'utf8'));
  const weapons = [...personalWeapons.map(w => ({ key: `gear/${w.id}`, en: w.en })), ...stratagems.filter(s => s.category === 'support').map(s => ({ key: `arsenal/${s.id}`, en: s.en }))];
  const byName = new Map(weapons.map(w => [norm(w.en), w.key]));
  const byBare = new Map();
  for (const w of weapons) byBare.set(bare(w.en), byBare.has(bare(w.en)) ? null : w.key);
  const recoil = {}, unmatched = [];
  for (const row of snapshot.rows) {
    if (/^CQC-/.test(row.name)) continue;
    const key = byName.get(norm(row.name)) ?? byBare.get(bare(row.name));
    if (!key) { unmatched.push(row.name); continue; }
    if (recoil[key]) throw new Error(`${row.name}: ${key} already has a recoil row`);
    recoil[key] = { drift: row.drift, climb: row.climb, ...(row.limit.join() !== '90,90' && { limit: row.limit }) };
  }
  const source = { page: snapshot.source, retrievedAt: snapshot.retrievedAt, writtenFor: snapshot.writtenFor, codeVerified: snapshot.codeVerified };
  return { source, recoil: Object.fromEntries(Object.entries(recoil).sort(([a], [b]) => a.localeCompare(b))), unmatched };
}

export const recoilText = ({ source, recoil }) => `// Generated by scripts/build-recoil.mjs from db/source/otl_recoil.json (helldiversotl.com/research/recoil). Do not edit.
// Base recoil per weapon: drift = how far the weapon kicks, climb = how far the view climbs, each [horizontal, vertical];
// limit = [start, end] of the upward angle over which vertical recoil eases off (left out when 90 / 90).
export const recoilSource = ${JSON.stringify(source)};
export const weaponRecoil = {
${Object.entries(recoil).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`).join('\n')}
};
`;

if (import.meta.url === `file:///${process.argv[1].replaceAll('\\', '/').replace(/^\//, '')}`) {
  const data = await buildRecoil();
  await writeFile(new URL('../dist/data/weapon-recoil.js', import.meta.url), recoilText(data));
  console.log(`dist/data/weapon-recoil.js: ${Object.keys(data.recoil).length} weapons. Not on the site: ${data.unmatched.join(', ') || 'none'}`);
}
