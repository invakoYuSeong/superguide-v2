// Copies the game's own Korean for the English strings this site needs into
// db/source/game_names_ko.json (see the naming rule in AGENTS.md). The input is
// an official US English -> Korean string table extracted from the game files
// (tab-separated: id, english, korean), with a stats.json next to it naming the
// game build. Strings are matched exactly, then ignoring case.
// With --planets <행성.json> (the game's planet_data table: planet names in Korean and
// English, internal biome, biome description) it also writes db/source/game_planets_ko.json.
// Usage: node scripts/tools/export-game-names.mjs <official_strings_us_ko.tsv> [--planets <행성.json>]
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { shipModules } from '../../dist/data/ship-modules.js';

const tsv = process.argv[2];
if (!tsv) throw new Error('Usage: node scripts/tools/export-game-names.mjs <official_strings_us_ko.tsv> [--planets <행성.json>]');
const planetsFile = process.argv.includes('--planets') ? process.argv[process.argv.indexOf('--planets') + 1] : null;
const build = JSON.parse(await readFile(join(dirname(tsv), 'stats.json'), 'utf8')).build;
const exact = new Map(), folded = new Map();
for (const line of (await readFile(tsv, 'utf8')).split(/\r?\n/).slice(1)) {
  const [, english, korean] = line.split('\t');
  if (!english || !korean) continue;
  const key = english.trim();
  if (!exact.has(key)) exact.set(key, korean.trim());
  if (!folded.has(key.toLowerCase())) folded.set(key.toLowerCase(), korean.trim());
}

const source = async name => JSON.parse(await readFile(new URL(`../../db/source/${name}`, import.meta.url), 'utf8'));
// Every English string the site takes Korean from, grouped by where it is used.
const boosters = Object.values((await source('booster_korean.json')).boosters);
const objectives = Object.values((await source('structure_objectives.json')).structures).flat();
const planet = await source('planet_korean.json');
const planetEntries = [...planet.conditions, ...planet.gloom, ...planet.modifiers, ...planet.events];
const wanted = {
  shipModules: shipModules.map(module => module.en),
  boosters: boosters.flatMap(booster => [booster.name, booster.description]).filter(Boolean),
  objectives: [...new Set(objectives.map(entry => entry.game))],
  planets: [...new Set(planetEntries.flatMap(entry => [entry.name, entry.description]))],
  status: planet.status.map(entry => entry.name).filter(Boolean),
};

const out = { note: 'Generated by scripts/tools/export-game-names.mjs from the game\'s official string table. Do not edit; re-run after a game update.', build, strings: {} };
const missing = [];
for (const [group, keys] of Object.entries(wanted)) {
  out.strings[group] = {};
  for (const key of keys) {
    const korean = exact.get(key) ?? folded.get(key.toLowerCase());
    if (korean) out.strings[group][key] = korean; else missing.push(`${group}: ${key}`);
  }
}
if (missing.length) throw new Error(`No Korean in the game table for:\n  ${missing.join('\n  ')}`);
await writeFile(new URL('../../db/source/game_names_ko.json', import.meta.url), JSON.stringify(out, null, 1) + '\n');
console.log(`game build ${build}: ${Object.values(out.strings).reduce((sum, group) => sum + Object.keys(group).length, 0)} strings`);

// Planet names and biome descriptions from the game's planet table.
if (planetsFile) {
  const table = JSON.parse(await readFile(planetsFile, 'utf8'));
  if (String(table.game_build) !== String(build)) throw new Error(`${planetsFile} is game build ${table.game_build}, the string table ${build}`);
  const planets = table['행성'].filter(row => row['한국어'] && row['영어']).map(row => ({ ko: row['한국어'], en: row['영어'], biome: row['생물군계'].split(' ')[0] }));
  // A biome's description is the one most of its planets carry (a few planets have their own story text).
  const biomes = {};
  for (const row of table['행성'].filter(row => row['설명(한국어)'] && row['설명(영어)'])) {
    const biome = row['생물군계'].split(' ')[0];
    const key = `${row['설명(영어)']}\t${row['설명(한국어)']}`;
    ((biomes[biome] ??= {})[key] = (biomes[biome][key] || 0) + 1);
  }
  const descriptions = Object.fromEntries(Object.entries(biomes).map(([biome, counts]) => {
    const [en, ko] = Object.entries(counts).sort((a, b) => b[1] - a[1])[0][0].split('\t');
    return [biome, { en, ko }];
  }));
  const outPlanets = { note: 'Generated by scripts/tools/export-game-names.mjs --planets from the game\'s planet table. Do not edit.', build, biomes: descriptions, planets };
  await writeFile(new URL('../../db/source/game_planets_ko.json', import.meta.url), JSON.stringify(outPlanets, null, 1) + '\n');
  console.log(`${planets.length} planets, ${Object.keys(descriptions).length} biome descriptions`);
}
