// Builds dist/data/superstore.js from the wiki Superstore page (db/source/wiki_superstore.json):
// 27 store pages as 3x2 boards with Super Credit prices. Weapons and armor link to the site's own
// entries (Korean names from there); capes, player cards and emotes take the game's Korean
// (db/source/game_names_ko.json, scripts/build-game-names.mjs). Unmatched names stay English.
// Usage: node scripts/build-superstore.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { parseSuperstore, superstoreGameKeys, SUPERSTORE_BOARD } from './superstore-parse.mjs';
import { warbonds } from '../dist/data/warbonds.js';
import { personalWeapons } from '../dist/data/personal-weapons.js';
import { armors } from '../dist/data/armor.js';

const read = async name => JSON.parse(await readFile(new URL(`../db/source/${name}`, import.meta.url), 'utf8'));
const wiki = await read('wiki_superstore.json');
const gameNames = (await read('game_names_ko.json')).strings.superstoreItems;
const { pages, listedTotal } = parseSuperstore(wiki.text);

const fold = text => String(text ?? '').toLowerCase();
// The store page title links the warbond's wiki page, the same page each warbond's `source` points to.
const warbondByPage = new Map(warbonds.map(warbond => [fold(decodeURIComponent(warbond.source.split('/wiki/')[1]).replaceAll('_', ' ')), warbond]));
const weaponByEn = new Map(personalWeapons.map(weapon => [fold(weapon.en), weapon]));
const armorByEn = new Map(armors.map(armor => [fold(armor.en), armor]));
const problems = [];

const out = pages.map(page => {
  if (page.layout.length) problems.push(`page ${page.number}: ${page.layout.join('; ')}`);
  const warbond = page.warbondPage ? warbondByPage.get(fold(page.warbondPage)) : null;
  if (page.warbondPage && !warbond) problems.push(`page ${page.number}: no warbond for ${page.warbondPage}`);
  if (!page.warbondPage && !page.warHorses) problems.push(`page ${page.number}: no title`);
  const items = page.items.map(item => {
    const entry = { name: item.name, kind: item.kind, cost: item.cost, image: item.image, link: item.link, col: item.col, row: item.row, colspan: item.colspan, rowspan: item.rowspan };
    if (item.cost == null) problems.push(`page ${page.number}: ${item.name} has no price`);
    if (item.kind === 'weapon') {
      const weapon = weaponByEn.get(fold(item.name));
      if (weapon) Object.assign(entry, { ref: { view: 'gear', id: weapon.id } });
      else problems.push(`page ${page.number}: weapon ${item.name} is not in personal-weapons`);
    } else if (item.kind === 'armor' || item.kind === 'helmet') {
      const armor = armorByEn.get(fold(item.base));
      if (armor) Object.assign(entry, { set: item.base, ref: { view: 'armor', id: armor.id }, ...(armor.nameStatus === 'confirmed' && { ko: armor.name }) });
      else problems.push(`page ${page.number}: armor set ${item.base} is not in armor.js`);
    } else {
      const ko = superstoreGameKeys(item).map(key => gameNames[key]).find(Boolean);
      if (ko) entry.ko = ko;
    }
    return entry;
  });
  const total = items.reduce((sum, item) => sum + (item.cost ?? 0), 0);
  return {
    number: page.number, warbondId: warbond?.id ?? null, warHorses: page.warHorses, items, total,
    ...(page.tableTotal != null && page.tableTotal !== total && { tableTotal: page.tableTotal }),
  };
});
if (problems.length) throw new Error(`build-superstore:\n  ${problems.join('\n  ')}`);
const grandTotal = out.reduce((sum, page) => sum + page.total, 0);
await writeFile(new URL('../dist/data/superstore.js', import.meta.url), `// Generated by scripts/build-superstore.mjs from the Helldivers Wiki Superstore page
// (CC BY-NC-SA 4.0). Do not edit.
export const superstoreSource = ${JSON.stringify({ page: wiki.source, revision: wiki.revision, checkedAt: wiki.retrievedAt })};
export const superstoreBoard = ${JSON.stringify(SUPERSTORE_BOARD)};
// Sum of every price, and the wiki's own "Total Cost" table (updated by hand on the wiki).
export const superstoreTotal = ${JSON.stringify({ sum: grandTotal, listed: listedTotal })};
export const superstorePages = ${JSON.stringify(out, null, 1)};
`);
console.log(`${out.length} pages, ${out.reduce((sum, page) => sum + page.items.length, 0)} items, ${grandTotal} SC (wiki lists ${listedTotal}); English only: ${out.flatMap(page => page.items).filter(item => !item.ko && !item.ref).map(item => item.name).join(', ') || 'none'}`);
