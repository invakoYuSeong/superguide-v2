// Builds dist/data/enemy-pages.js: per enemy on the enemy view, the wiki infobox fire damage
// multiplier and stagger threshold, its subfaction (faction picks guide id) and the Korean/English
// summaries of the wiki Spawning, Behavior and Tactical Information sections.
// Inputs: db/source/wiki_enemy_pages.json (scripts/fetch-enemy-pages.mjs) and
// db/source/enemy_behavior_korean.json (summaries, each tied to the wiki revision it was written from).
// Usage: node scripts/build-enemy-pages.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { enemies } from '../dist/data/combat-data.js';
import { factionGuides } from '../dist/data/faction-data.js';
import { pageTitle, infoboxNumber, reinforcementOf } from './enemy-page-title.mjs';

const read = async path => JSON.parse(await readFile(new URL(path, import.meta.url), 'utf8'));
const wiki = await read('../db/source/wiki_enemy_pages.json');
const summaries = await read('../db/source/enemy_behavior_korean.json');
// Wiki infobox `faction` -> faction picks guide id (the three main factions have none).
const SUBFACTIONS = {
  'Predator Strain': 'predator', 'Spore Burst Strain': 'spore-burst', 'Rupture Strain': 'rupture', 'Caustic Strain': 'caustic', 'Noxious Strain': 'noxious',
  'Jet Brigade': 'jet-brigade', 'Incineration Corps': 'incineration', 'Cyborg Legion': 'cyborgs',
  'Vote Snatchers': 'vote-snatchers', 'Mindless Masses': 'mindless', 'Appropriators': 'appropriators', 'Invasion Fleet': 'invasion',
};
const MAIN = new Set(['Terminids', 'Automatons', 'Illuminate']);
const guideIds = new Set(factionGuides.map(guide => guide.id));

// Never blocks a build (user decision 2026-11-19): an enemy whose page is not fetched yet has no entry,
// one without a summary shows no Spawning/Behavior, and a summary written from an older wiki revision
// is kept as it is (summaryRevision) until someone rewrites it. Each case is listed as a note.
const out = {};
const notes = [];
for (const enemy of enemies) {
  const title = pageTitle(enemy);
  const page = wiki.pages[title];
  if (!page) { notes.push(`${enemy.id}: wiki page ${title} not fetched (run fetch-enemy-pages)`); continue; }
  const summary = summaries[title];
  if (!summary) notes.push(`${title}: no summary in enemy_behavior_korean.json`);
  else if (summary.revision !== page.revision) notes.push(`${title}: summary written from revision ${summary.revision}, wiki is now ${page.revision}`);
  if (page.faction && !MAIN.has(page.faction) && !SUBFACTIONS[page.faction]) notes.push(`${title}: unknown faction ${page.faction} (no subfaction shown)`);
  const subfaction = guideIds.has(SUBFACTIONS[page.faction]) ? SUBFACTIONS[page.faction] : null;
  for (const [key, value] of [['fire_mult', page.fireMult], ['stagger_req', page.staggerReq]]) if (value != null && infoboxNumber(value) == null) notes.push(`${title}: ${key} "${value}" is not a number (shown as unverified)`);
  const lines = key => summary?.[key] ?? [];
  out[enemy.id] = {
    page: title, revision: page.revision, ...(summary && { summaryRevision: summary.revision }), subfaction,
    fireMult: infoboxNumber(page.fireMult), staggerReq: infoboxNumber(page.staggerReq),
    // Calls reinforcements (wiki Behavior text): 'breach' | 'dropship' | 'warp'; left out when it does not.
    ...(reinforcementOf(page) && { reinforcements: reinforcementOf(page) }),
    spawning: lines('spawning').map(line => line.ko), spawningEn: lines('spawning').map(line => line.en),
    behavior: lines('behavior').map(line => line.ko), behaviorEn: lines('behavior').map(line => line.en),
    // Tactics (wiki Tactical Information of the same revision), written only for some large enemies; left out when none.
    ...(lines('tactics').length && { tactics: lines('tactics').map(line => line.ko), tacticsEn: lines('tactics').map(line => line.en) }),
  };
}
await writeFile(new URL('../dist/data/enemy-pages.js', import.meta.url), `// Generated by scripts/build-enemy-pages.mjs from Helldivers Wiki enemy pages (infobox fire_mult,
// stagger_req, faction; Spawning, Behavior and Tactical Information summarized in db/source/enemy_behavior_korean.json).
// Do not edit.
export const enemyPagesCheckedAt = ${JSON.stringify(wiki.retrievedAt)};
export const enemyPages = ${JSON.stringify(out, null, 1)};
`);
console.log(`${Object.keys(out).length} enemies${notes.length ? `; to look at:\n  ${notes.join('\n  ')}` : ''}`);
